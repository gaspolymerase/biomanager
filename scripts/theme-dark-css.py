#!/usr/bin/env python3
"""Write app/static/theme-dark.css: dark mode for whoever chooses it.

The stylesheets give dark mode as the computer's, under
`@media (prefers-color-scheme: dark) { :root:not([data-theme="light"]) … }`.
Someone who picks Dark in Settings → Appearance on a light computer gets
`<html data-theme="dark">` (app/appearance.py), and needs the same rules
without the media query. Many have that copy beside them already; this
writes the rest, so each is written once, in its own stylesheet.

    python3 scripts/theme-dark-css.py

Run it after changing a dark-mode rule; tests/test_appearance.py checks the
file is current. Rules that use @apply are Tailwind's to compile and are
left out: give those their `:root[data-theme="dark"]` copy in place.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "app" / "static" / "theme-dark.css"
SOURCES = ["frontend/src/tailwind.css", "frontend/src/styles.css", "frontend/src/blocks.css",
           "app/static/calendar.css", "app/static/home-layouts.css", "app/static/loader.css",
           "app/static/plasmid.css", "app/static/appearance.css"]

MEDIA = "@media (prefers-color-scheme: dark)"
SYSTEM = ':not([data-theme="light"])'
CHOSEN = '[data-theme="dark"]'


def _blocks(text: str, i: int = 0):
    """Yield (prelude, body, children) for each block at this level, and the
    index where the level ends. Declarations between blocks are skipped."""
    out, start = [], i
    while i < len(text):
        c = text[i]
        if c == "{":
            prelude = text[start:i].strip().split(";")[-1].strip()
            children, j = _blocks(text, i + 1)
            out.append((prelude, text[i + 1:j - 1], children))
            i = start = j
        elif c == "}":
            return out, i + 1
        elif c == ";":
            start = i + 1
            i += 1
        else:
            i += 1
    return out, i


def _selectors(prelude: str) -> list[str]:
    """Split a selector list at its top-level commas (not inside :is(…))."""
    parts, depth, cur = [], 0, ""
    for c in prelude:
        depth += c in "(["
        depth -= c in ")]"
        if c == "," and depth == 0:
            parts.append(cur.strip())
            cur = ""
        else:
            cur += c
    return parts + [cur.strip()]


def rules(path: Path):
    # Comments out, strings kept: "app/templates/**/*.html" is not a comment.
    text = re.sub(r'"(?:\\.|[^"\\])*"|/\*.*?\*/', lambda m: m.group(0) if m.group(0)[0] == '"' else "",
                  path.read_text(encoding="utf-8"), flags=re.S)
    tree, _ = _blocks(text)
    found, have = [], set()

    def selector_set(prelude: str) -> frozenset:
        return frozenset(" ".join(s.split()) for s in _selectors(prelude))

    def walk(nodes, layer):
        for prelude, body, children in nodes:
            have.add(selector_set(prelude))
            if prelude.startswith("@layer"):
                walk(children, prelude.split()[1])
            elif prelude == MEDIA:
                for sel, decls, inner in children:
                    if inner or "@apply" in decls:
                        continue
                    sels = _selectors(sel)
                    if all(SYSTEM in s for s in sels):
                        found.append((layer, ", ".join(s.replace(SYSTEM, CHOSEN) for s in sels), decls))
            else:
                walk(children, layer)

    walk(tree, "")
    # Rules already written out beside the media query are left alone.
    return [r for r in found if selector_set(r[1]) not in have]


def build() -> str:
    out = ["/* Generated by scripts/theme-dark-css.py: dark mode for whoever chooses it in",
           "   Settings → Appearance, copied from the stylesheets' own dark mode. Don't edit. */"]
    for source in SOURCES:
        found = rules(ROOT / source)
        if not found:
            continue
        out.append(f"\n/* {source} */")
        for layer, selector, decls in found:
            lines = [ln.strip() for ln in decls.strip().splitlines() if ln.strip()]
            rule = f"{selector} {{\n  " + "\n  ".join(lines) + "\n}"
            out.append(f"@layer {layer} {{\n{rule}\n}}" if layer else rule)
    return "\n".join(out) + "\n"


def main() -> None:
    css = build()
    if "--check" in sys.argv:
        sys.exit(0 if OUT.read_text(encoding="utf-8") == css else 1)
    OUT.write_text(css, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
